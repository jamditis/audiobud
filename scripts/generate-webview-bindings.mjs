import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fullBindings = readFileSync(resolve(root, "src/bindings.ts"), "utf8");
const checkOnly = process.argv.includes("--check");

function findMatchingBrace(source, openIndex) {
  let depth = 0;
  let quote = null;
  let lineComment = false;
  let blockComment = false;

  for (let index = openIndex; index < source.length; index += 1) {
    const character = source[index];
    const next = source[index + 1];

    if (lineComment) {
      if (character === "\n") lineComment = false;
      continue;
    }
    if (blockComment) {
      if (character === "*" && next === "/") {
        blockComment = false;
        index += 1;
      }
      continue;
    }
    if (quote) {
      if (character === "\\") {
        index += 1;
      } else if (character === quote) {
        quote = null;
      }
      continue;
    }
    if (character === "/" && next === "/") {
      lineComment = true;
      index += 1;
      continue;
    }
    if (character === "/" && next === "*") {
      blockComment = true;
      index += 1;
      continue;
    }
    if (character === '"' || character === "'" || character === "`") {
      quote = character;
      continue;
    }
    if (character === "{") depth += 1;
    if (character === "}") {
      depth -= 1;
      if (depth === 0) return index;
    }
  }

  throw new Error(
    `Unbalanced generated binding starting at offset ${openIndex}`,
  );
}

const commandsMarker = "export const commands = {";
const commandsStart = fullBindings.indexOf(commandsMarker);
if (commandsStart < 0)
  throw new Error("src/bindings.ts has no commands object");
const commandsOpen = fullBindings.indexOf("{", commandsStart);
const commandsEnd = findMatchingBrace(fullBindings, commandsOpen);
const commandsSource = fullBindings.slice(commandsOpen + 1, commandsEnd);

function findMethodBodyOpen(source, start) {
  let parentheses = 0;
  let angles = 0;
  let brackets = 0;

  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (character === "(") parentheses += 1;
    else if (character === ")") parentheses -= 1;
    else if (character === "<") angles += 1;
    else if (character === ">") angles -= 1;
    else if (character === "[") brackets += 1;
    else if (character === "]") brackets -= 1;
    else if (
      character === "{" &&
      parentheses === 0 &&
      angles === 0 &&
      brackets === 0
    ) {
      return index;
    }
  }

  throw new Error(`Could not find generated command body at offset ${start}`);
}

function extractCommand(name) {
  const marker = `async ${name}(`;
  const start = commandsSource.indexOf(marker);
  if (start < 0) throw new Error(`src/bindings.ts has no ${name} command`);
  if (commandsSource.indexOf(marker, start + marker.length) >= 0) {
    throw new Error(`src/bindings.ts contains more than one ${name} command`);
  }

  const bodyOpen = findMethodBodyOpen(commandsSource, start);
  const bodyEnd = findMatchingBrace(commandsSource, bodyOpen);
  const commaEnd =
    commandsSource[bodyEnd + 1] === "," ? bodyEnd + 2 : bodyEnd + 1;
  return commandsSource.slice(start, commaEnd).trim();
}

const eventsMarker = "export const events = __makeEvents__<{";
const eventsStart = fullBindings.indexOf(eventsMarker, commandsEnd);
if (eventsStart < 0) throw new Error("src/bindings.ts has no events object");
const eventTypesStart = eventsStart + eventsMarker.length;
const eventTypesEnd = fullBindings.indexOf("}>({", eventTypesStart);
const eventNamesEnd = fullBindings.indexOf("})", eventTypesEnd);
if (eventTypesEnd < 0 || eventNamesEnd < 0) {
  throw new Error("src/bindings.ts has a malformed events object");
}
const eventTypesSource = fullBindings.slice(eventTypesStart, eventTypesEnd);
const eventNamesSource = fullBindings.slice(eventTypesEnd + 4, eventNamesEnd);

function extractEvent(name) {
  const escapedName = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const payloadMatch = eventTypesSource.match(
    new RegExp(`(?:^|\\n)\\s*${escapedName}\\s*:\\s*([^,\\n]+)`),
  );
  const nameMatch = eventNamesSource.match(
    new RegExp(`(?:^|\\n)\\s*${escapedName}\\s*:\\s*("[^"]+")`),
  );
  if (!payloadMatch || !nameMatch) {
    throw new Error(`src/bindings.ts has no complete ${name} event`);
  }
  return { payload: payloadMatch[1].trim(), wireName: nameMatch[1] };
}

function renderEvent(name) {
  const event = extractEvent(name);
  return `${name}: {
    listen(callback: EventCallback<${event.payload}>) {
      return listen(${event.wireName}, callback);
    },
  },`;
}

const banner = `// This file is generated by scripts/generate-webview-bindings.mjs.
// Edit the Rust command contract or the generator, then run bun run bindings:generate.
`;

const outputTargetLockEvent = renderEvent("outputTargetLockEvent");
const transcriptDeliveredEvent = renderEvent("transcriptDeliveredEvent");

const templates = {
  "src/bindings/shared.ts": `${banner}
import { invoke as TAURI_INVOKE } from "@tauri-apps/api/core";
import { listen, type EventCallback } from "@tauri-apps/api/event";
import type { OutputTargetLockEvent } from "../bindings";

export const commands = {
  ${extractCommand("getAppLanguage")}
  ${extractCommand("getOutputTargetLock")}
  ${extractCommand("releaseOutputTargetLock")}
};

export const events = {
  ${outputTargetLockEvent}
};
`,
  "src/bindings/overlay.ts": `${banner}
import { invoke as TAURI_INVOKE } from "@tauri-apps/api/core";
import { listen, type EventCallback } from "@tauri-apps/api/event";
import type { TranscriptDeliveredEvent } from "../bindings";

export const commands = {
  ${extractCommand("recordingOverlayReady")}
  ${extractCommand("cancelOperation")}
};

export const events = {
  ${transcriptDeliveredEvent}
};
`,
  "src/bindings/window-picker.ts": `${banner}
import { invoke as TAURI_INVOKE } from "@tauri-apps/api/core";
import type { PickArmed, PickerGesture, PickerWindow } from "../bindings";

export const commands = {
  ${extractCommand("listPickerWindows")}
  ${extractCommand("resolveWindowPick")}
};
`,
};

const outputs = Object.fromEntries(
  await Promise.all(
    Object.entries(templates).map(async ([path, contents]) => [
      path,
      await format(contents, { parser: "typescript" }),
    ]),
  ),
);

let stale = false;
for (const [relativePath, contents] of Object.entries(outputs)) {
  const path = resolve(root, relativePath);
  if (checkOnly) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // Report the same actionable stale-output error for a missing file.
    }
    if (current !== contents) {
      console.error(`${relativePath} is stale; run bun run bindings:generate`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
}

if (stale) process.exit(1);
